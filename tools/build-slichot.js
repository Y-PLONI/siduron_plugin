/* build-slichot.js — builds data/slichot-data.js (window.SIDURON_SLICHOT) from
 * tools/data-overrides/slichot_ashkenaz.json + slichot_ashkenaz_aseret.json
 * (סליחות נוסח אשכנז/ליטא, converted from seforim.db book 1393).
 *   node tools/build-slichot.js
 * Output: { ashkenaz: { day1..day7, erev_rosh_hashana, tzom_gedalia, ayt_mon..ayt_thu,
 *   erev_yom_kippur } }, each a flat segment list [{kind, text}] with kind
 *   header | instruction | text (title → header). The item to show is chosen
 *   at runtime from the slichot_* day flags (js/calendar.js, js/services.js).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const OV = path.join(__dirname, 'data-overrides');
const out = { ashkenaz: {} };
['slichot_ashkenaz', 'slichot_ashkenaz_aseret'].forEach(function (f) {
  JSON.parse(fs.readFileSync(path.join(OV, f + '.json'), 'utf8')).items.forEach(function (it) {
    out.ashkenaz[it.id] = it.segments.map(function (s) {
      return { kind: s.kind === 'title' ? 'header' : s.kind, text: String(s.text).replace(/\u2003/g, ' ') };
    });
  });
});
const header = '/* slichot-data.js — GENERATED by tools/build-slichot.js. Do not edit by hand.\n' +
  ' * סליחות נוסח אשכנז (ליטא): ימי אלול, ערב ר"ה, צום גדליה, עשי"ת, ערב יה"כ.\n */\n';
fs.writeFileSync(path.join(__dirname, '..', 'data', 'slichot-data.js'),
  header + 'window.SIDURON_SLICHOT = ' + JSON.stringify(out) + ';\n');
console.log('items:', Object.keys(out.ashkenaz).length);
